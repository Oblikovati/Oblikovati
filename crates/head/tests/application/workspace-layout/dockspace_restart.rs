#[test]
fn docked_tool_tabs_and_bounds_survive_a_native_restart() {
    let mut world = ApplicationWorld::with_asset_tools_closed();
    super::browser_feature::open_visible_extruded_part(&mut world);
    let initial = viewport(&mut world);
    open_toolbar_tool(&mut world, "Material Browser");
    let (position, size) = window_geometry("Material Browser").unwrap();
    let start = [
        (position[0] + size[0] * 0.4) as i32,
        (position[1] + 10.) as i32,
    ];
    native_drag(
        &mut world,
        start,
        [
            initial[2] as i32 - 15,
            ((initial[1] + initial[3]) / 2) as i32,
        ],
    );
    let docked_area = viewport(&mut world);
    open_toolbar_tool(&mut world, "Appearance Browser");
    let (source, source_size) = window_geometry("Appearance Browser").unwrap();
    let (destination, destination_size) = window_geometry("Material Browser").unwrap();
    let start = [
        (source[0] + source_size[0] * 0.4) as i32,
        (source[1] + 10.) as i32,
    ];
    let target = [
        (destination[0] + destination_size[0] * 0.5) as i32,
        (destination[1] + 10.) as i32,
    ];
    native_drag(&mut world, start, target);
    let node = super::super::diagnostics::window_dock_id("Material Browser").unwrap();
    assert_eq!(
        super::super::diagnostics::window_dock_id("Appearance Browser"),
        Some(node)
    );
    let selected = super::super::diagnostics::window_dock_tab_visible("Appearance Browser");
    world.reopen_application();
    world.add_part();
    world.pump(Vec::new());
    let restored = super::super::diagnostics::window_dock_id("Material Browser").unwrap();
    assert_ne!(restored, 0, "material browser must restore its dock");
    assert_eq!(
        super::super::diagnostics::window_dock_id("Appearance Browser"),
        Some(restored)
    );
    assert_eq!(
        super::super::diagnostics::window_dock_tab_visible("Appearance Browser"),
        selected
    );
    assert_eq!(
        viewport(&mut world),
        docked_area,
        "workspace bounds must survive restart"
    );
    world.save_capture("workspace-dock-restored");
    let (minimum, maximum) =
        super::super::diagnostics::window_dock_tab_bounds("Appearance Browser").unwrap();
    let close = [
        maximum[0] - (maximum[1] - minimum[1]) * 0.5,
        (minimum[1] + maximum[1]) * 0.5,
    ];
    world.click(super::super::diagnostics::pointer_pixels(close));
    world.pump(Vec::new());
    assert!(window_geometry("Appearance Browser").is_none());
    world.reopen_application();
    world.add_part();
    world.pump(Vec::new());
    assert!(
        window_geometry("Appearance Browser").is_none(),
        "closed tab must remain closed after restart"
    );
    assert_ne!(
        super::super::diagnostics::window_dock_id("Material Browser"),
        Some(0)
    );
    world.close();
}

#[test]
fn floating_tool_position_and_size_survive_a_native_restart() {
    let mut world = ApplicationWorld::with_asset_tools_closed();
    world.add_part();
    open_toolbar_tool(&mut world, "Material Browser");
    let (position, size) = window_geometry("Material Browser").unwrap();
    let start = [
        (position[0] + size[0] * 0.4) as i32,
        (position[1] + 10.) as i32,
    ];
    native_drag(&mut world, start, [700, 420]);
    assert_eq!(
        super::super::diagnostics::window_dock_id("Material Browser"),
        Some(0)
    );
    let (position, size) = window_geometry("Material Browser").unwrap();
    let corner = [
        (position[0] + size[0] - 4.) as i32,
        (position[1] + size[1] - 4.) as i32,
    ];
    native_drag(&mut world, corner, [corner[0] + 70, corner[1] + 60]);
    let (position, resized) = window_geometry("Material Browser").unwrap();
    assert!(
        resized[0] > size[0] + 30. && resized[1] > size[1] + 30.,
        "window size {size:?} -> {resized:?}"
    );
    let size = resized;
    world.reopen_application();
    world.add_part();
    world.pump(Vec::new());
    let (restored_position, restored_size) = window_geometry("Material Browser").unwrap();
    for axis in 0..2 {
        assert!(
            (position[axis] - restored_position[axis]).abs() <= 1.,
            "position {position:?} -> {restored_position:?}"
        );
        assert!(
            (size[axis] - restored_size[axis]).abs() <= 1.,
            "size {size:?} -> {restored_size:?}"
        );
    }
    world.close();
}

#[test]
fn previous_inner_dock_settings_restore_after_reparenting() {
    let mut world = ApplicationWorld::new();
    world.close();
    // Generated by the old ImGui 1.89.2 host after a programmatic inner split (#4071).
    let bytes = include_bytes!("fixtures/legacy-inner-dock.json");
    std::fs::write(
        world.preferences_directory().join("workspace-layout.json"),
        bytes,
    )
    .unwrap();
    world.reopen_application();
    world.add_part();
    world.pump(Vec::new());
    let node = super::super::diagnostics::window_dock_id("Material Browser").unwrap();
    assert_ne!(node, 0, "old material browser dock must restore");
    assert_eq!(viewport(&mut world), [361, 149, 1061, 850]);
    world.close();
}

#[test]
fn browser_closed_from_its_contents_returns_to_shared_dock() {
    let mut world = ApplicationWorld::with_asset_tools_closed();
    super::browser_feature::open_visible_extruded_part(&mut world);
    let initial = viewport(&mut world);
    open_toolbar_tool(&mut world, "Appearance Browser");
    let (position, size) = window_geometry("Appearance Browser").unwrap();
    let start = [
        (position[0] + size[0] * 0.4) as i32,
        (position[1] + 10.) as i32,
    ];
    let target = [
        initial[2] as i32 - 15,
        ((initial[1] + initial[3]) / 2) as i32,
    ];
    native_drag(&mut world, start, target);
    open_toolbar_tool(&mut world, "Material Browser");
    let (source, source_size) = window_geometry("Material Browser").unwrap();
    let (destination, destination_size) = window_geometry("Appearance Browser").unwrap();
    let start = [
        (source[0] + source_size[0] * 0.4) as i32,
        (source[1] + 10.) as i32,
    ];
    let target = [
        (destination[0] + destination_size[0] * 0.5) as i32,
        (destination[1] + 10.) as i32,
    ];
    native_drag(&mut world, start, target);
    let node = super::super::diagnostics::window_dock_id("Appearance Browser").unwrap();
    assert_ne!(node, 0);
    assert_eq!(
        super::super::diagnostics::window_dock_id("Material Browser"),
        Some(node)
    );
    select_dock_tab(&mut world, "Material Browser");
    world.run_in_window("Material Browser", "Assigntopart");
    select_dock_tab(&mut world, "Appearance Browser");
    let (min, max) =
        super::super::diagnostics::window_dock_tab_bounds("Appearance Browser").unwrap();
    let close = [max[0] - 8., (min[1] + max[1]) * 0.5];
    world.hover(super::super::diagnostics::pointer_pixels(close));
    super::super::x11_input::click(super::super::diagnostics::pointer_pixels(close));
    assert_remaining_tab_without_blank_frame(&mut world);
    world.save_capture("material-after-appearance-close");
    assert_eq!(
        super::super::diagnostics::window_dock_tab_visible("Material Browser"),
        Some(true)
    );
    world.run_in_window("Material Browser", "Assigntopart");
    native_click_label(&mut world, "View");
    native_click_label(&mut world, "User Interface");
    native_click_label(&mut world, "Appearance Browser");
    world.pump(Vec::new());
    assert_eq!(
        super::super::diagnostics::window_dock_id("Appearance Browser"),
        Some(node)
    );
    select_dock_tab(&mut world, "Appearance Browser");
    world.run_in_window("Appearance Browser", "Assigntopart");
    world.save_capture("appearance-restored-to-shared-dock");
    world.close();
}

fn assert_remaining_tab_without_blank_frame(world: &mut ApplicationWorld) {
    for _ in 0..8 {
        let app = world.app();
        crate::frames::run_frames(
            &mut app.window,
            crate::HeadOptions { frames: Some(1) },
            &mut app.owner,
        )
        .unwrap();
        if window_geometry("Appearance Browser").is_none() {
            assert_eq!(
                super::super::diagnostics::window_dock_tab_visible("Material Browser"),
                Some(true),
                "the remaining tab must be visible in the first frame after close"
            );
            return;
        }
    }
    panic!("Appearance Browser: expected close within eight frames");
}

pub(super) fn select_dock_tab(world: &mut ApplicationWorld, title: &str) {
    let (min, max) = super::super::diagnostics::window_dock_tab_bounds(title).unwrap();
    let center = [(min[0] + max[0]) * 0.5, (min[1] + max[1]) * 0.5];
    let point = super::super::diagnostics::pointer_pixels(center);
    if world.app().window.native.view.uses_wayland() {
        world.click(point);
    } else {
        super::super::x11_input::click(point);
        world.pump(Vec::new());
    }
    assert_eq!(
        super::super::diagnostics::window_dock_tab_visible(title),
        Some(true)
    );
}

pub(super) fn native_click_label(world: &mut ApplicationWorld, label: &str) {
    let center = world.run(label).center();
    super::super::x11_input::click(super::super::diagnostics::pointer_pixels(center));
    world.pump(Vec::new());
}


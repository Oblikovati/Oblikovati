macro_rules! owned_keyboard_keys {
    ($($key:ident),+ $(,)?) => {
        /// Named keyboard positions shared by the native and GUI input boundaries.
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub enum ViewportPhysicalKey { $($key),+ }
        impl ViewportPhysicalKey {
            /// Enumerate the admitted keys; example: `ViewportPhysicalKey::ALL.contains(&key)`.
            pub const ALL: &[Self] = &[$(Self::$key),+];
        }
    };
}

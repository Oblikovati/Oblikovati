#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn physical_key_positions_keep_keypad_and_modifiers_distinct() {
        assert_eq!(key(2), Some(ViewportPhysicalKey::Alpha1));
        assert_eq!(key(79), Some(ViewportPhysicalKey::Keypad1));
        assert_eq!(key(97), Some(ViewportPhysicalKey::RightCtrl));
        assert_eq!(key(0), None);
    }
}

// Command gen writes script/console/apidoc/data_gen.go from the API contract: it resolves the
// api module's source directory, parses its scriptable wire methods (summary + argument fields)
// via script/luadoc, and emits a Go table the editor embeds for signature help and hover docs.
// Run via `go generate ./script/console/apidoc` whenever the public API surface changes.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"strings"
	"text/template"

	"oblikovati.org/script/luadoc"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "apidoc/gen:", err)
		os.Exit(1)
	}
}

func run() error {
	dir, err := apiDir()
	if err != nil {
		return err
	}
	methods, err := luadoc.Methods(dir)
	if err != nil {
		return err
	}
	src, err := render(methods)
	if err != nil {
		return err
	}
	return os.WriteFile("data_gen.go", src, 0o644)
}

// apiDir resolves the on-disk root of the oblikovati.org/api module.
func apiDir() (string, error) {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "oblikovati.org/api").Output()
	if err != nil {
		return "", fmt.Errorf("resolve api module dir: %w", err)
	}
	return strings.TrimSpace(string(out)), nil
}

// render formats the doc table as gofmt-ed Go source.
func render(methods []luadoc.Method) ([]byte, error) {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, methods); err != nil {
		return nil, err
	}
	return format.Source(buf.Bytes())
}

// tmpl emits the generated var. luadoc.Method fields map directly onto apidoc.Doc/Param.
var tmpl = template.Must(template.New("data").Parse(`// SPDX-License-Identifier: GPL-2.0-only

// Code generated by script/console/apidoc/gen; DO NOT EDIT.

package apidoc

// generated is the build-time snapshot of the host API's scriptable methods.
var generated = []Doc{
{{- range .}}
	{Wire: {{printf "%q" .Wire}}, Summary: {{printf "%q" .Summary}}, Params: []Param{
		{{- range .Args}}{Name: {{printf "%q" .Name}}, Type: {{printf "%q" .Type}}}, {{end -}}
	}},
{{- end}}
}
`))
